"""Render systemd drop-ins from resolved limits. Pure functions, no I/O."""

from __future__ import annotations

from ..config import UNLIMITED, REDIS_POLICIES, ConfigError, normalize_value
from ..da_users import require_username

ACCOUNTING = (
    "CPUAccounting=yes",
    "MemoryAccounting=yes",
    "IOAccounting=yes",
    "TasksAccounting=yes",
)


def properties(values: dict[str, str], io_device: str | None) -> list[str]:
    """systemd PROPERTY=VALUE pairs for one user slice, in a fixed order.

    The same list feeds the drop-in file and `systemctl set-property`, so the
    two can never disagree.
    """
    # systemd resets CPUQuota with an empty value, not with "infinity".
    cpu = "" if values["cpu_quota"] == UNLIMITED else values["cpu_quota"]
    pairs = [
        f"CPUQuota={cpu}",
        f"MemoryHigh={values['memory_high']}",
        f"MemoryMax={values['memory_max']}",
    ]
    if io_device is not None:
        pairs += [
            f"IOReadBandwidthMax={io_device} {values['io_read_bw']}",
            f"IOWriteBandwidthMax={io_device} {values['io_write_bw']}",
            f"IOReadIOPSMax={io_device} {values['iops_read']}",
            f"IOWriteIOPSMax={io_device} {values['iops_write']}",
        ]
    pairs.append(f"TasksMax={values['tasks_max']}")
    return pairs


def render_dropin(user: str, uid: int, values: dict[str, str], io_device: str | None) -> str:
    lines = [
        f"# Generated by da-plus for user {user} (UID {uid}). Do not edit.",
        "[Slice]",
        *ACCOUNTING,
        *properties(values, io_device),
    ]
    return "\n".join(lines) + "\n"


def redis_marker(user: str, uid: int) -> str:
    require_username(user)
    if not isinstance(uid, int) or uid < 0:
        raise ValueError("Redis UID must be a nonnegative integer")
    return f"# Generated by da-plus redis-user for {user} (UID {uid}). Do not edit."


def _redis_quote(value: str) -> str:
    if any(character in value for character in "\r\n\0"):
        raise ValueError("Redis renderer values must not contain control characters")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _unit_quote(value: str) -> str:
    return _redis_quote(value).replace("%", "%%").replace("$", "$$")


def render_redis_unit(user: str, uid: int, binary: str, *, data_dir: str | None = None) -> str:
    """Render an isolated, socket-only user's unit without touching systemd."""
    directory = data_dir or f"/var/lib/da-plus/redis/{user}"
    return "\n".join([
        redis_marker(user, uid), "[Unit]", f"Description=da-plus Redis for {user}",
        "After=local-fs.target", "", "[Service]", "Type=simple", f"User={user}",
        f"Slice=user-{uid}.slice", f"RuntimeDirectory=da-plus-redis/{user}",
        "RuntimeDirectoryMode=0700", f"ExecStart={_unit_quote(binary)} {_unit_quote(directory + '/redis.conf')}",
        "Restart=on-failure", "UMask=0077", "", "[Install]", "WantedBy=multi-user.target",
    ]) + "\n"


def render_redis_conf(user: str, uid: int, settings: dict, password: str, *,
                      data_dir: str | None = None, socket_path: str | None = None) -> str:
    """Pure Redis configuration: TCP and AOF are always disabled."""
    memory = normalize_value("memory_max", settings["maxmemory"], "redis.maxmemory")
    policy = settings.get("maxmemory_policy", "allkeys-lru")
    persistence = settings.get("persistence", "off")
    if memory == UNLIMITED or policy not in REDIS_POLICIES or persistence not in ("off", "rdb"):
        raise ConfigError("invalid Redis memory, policy or persistence")
    if not password:
        raise ValueError("Redis password must not be empty")
    return "\n".join([
        redis_marker(user, uid),
        f"unixsocket {_redis_quote(socket_path or f'/run/da-plus-redis/{user}/redis.sock')}",
        "unixsocketperm 700", "port 0", "bind none", f"requirepass {_redis_quote(password)}",
        f"maxmemory {memory}", f"maxmemory-policy {policy}",
        f"dir {_redis_quote(data_dir or f'/var/lib/da-plus/redis/{user}')}",
        "daemonize no", "appendonly no",
        'save ""' if persistence == "off" else "save 900 1 300 10 60 10000",
    ]) + "\n"
